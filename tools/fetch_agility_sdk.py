"""
Downloads and extracts the D3D12 Agility SDK NuGet package for use in Dawn.

Usage:
    python3 tools/fetch_agility_sdk.py [--version <version>|--latest] [--output <path>] [--force]

After running, the Agility SDK headers and binaries will be available at the
specified output path (default: third_party/agility_sdk).

The script also generates a C header (agility_sdk_version.h) so that
AgilitySDK.cpp always exports the correct D3D12SDKVersion matching the
downloaded package, without any manual hard-coding.
"""

import argparse
import io
import json
import os
import sys
import urllib.request
import zipfile

package_id = "Microsoft.Direct3D.D3D12"
DEFAULT_VERSION = "1.619.1"
DEFAULT_OUTPUT = os.path.join("third_party", "agility_sdk")


def get_latest_version():
    """Query NuGet for the latest stable version of the Agility SDK."""
    url = (f"https://api.nuget.org/v3-flatcontainer/"
           f"{package_id.lower()}/index.json")
    print(f"Querying latest version from {url} ...")
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            data = json.loads(response.read())
            versions = data.get("versions", [])
            # Filter out pre-release versions (those containing '-')
            stable = [v for v in versions if "-" not in v]
            if not stable:
                print("ERROR: no stable versions found")
                sys.exit(1)
            latest = stable[-1]
            print(f"Latest stable version: {latest}")
            return latest
    except Exception as e:
        print(f"ERROR: Failed to query latest version: {e}")
        sys.exit(1)


def sdk_version_from_package_version(package_version):
    """Extract the D3D12SDKVersion integer from a package version string.

    The NuGet package version has the form ``<major>.<sdk_version>.<patch>``.
    For example ``1.619.1`` → SDK version **619**.
    """
    parts = package_version.split(".")
    if len(parts) < 2:
        raise ValueError(f"Cannot parse SDK version from '{package_version}'")
    return int(parts[1])


def write_version_header(output_path, package_version):
    """Generate agility_sdk_version.h with the correct D3D12SDKVersion."""
    sdk_ver = sdk_version_from_package_version(package_version)
    header_path = os.path.join(output_path, "agility_sdk_version.h")
    content = (
        "// Auto-generated by tools/fetch_agility_sdk.py – DO NOT EDIT.\n"
        f"// Package: {package_id} v{package_version}\n"
        "#ifndef AGILITY_SDK_VERSION_H_\n"
        "#define AGILITY_SDK_VERSION_H_\n"
        f"#define AGILITY_SDK_VERSION {sdk_ver}u\n"
        "#endif  // AGILITY_SDK_VERSION_H_\n")
    os.makedirs(output_path, exist_ok=True)
    with open(header_path, "w") as f:
        f.write(content)
    print(f"Generated {header_path}  (D3D12SDKVersion = {sdk_ver})")


def download_and_extract(force, version, output_path):
    """Download the Agility SDK NuGet package and extract it."""
    stamp = os.path.join(output_path, f"{version}.stamp")

    if os.path.exists(stamp) and not force:
        print(f"Agility SDK {version} already present at {output_path} "
              f"(use --force to re-download)")
        # Still regenerate the header in case it was deleted.
        write_version_header(output_path, version)
        return

    nuget_url = (f"https://www.nuget.org/api/v2/package/"
                 f"{package_id}/{version}")
    print(f"Downloading {package_id} v{version} from {nuget_url} ...")

    try:
        with urllib.request.urlopen(nuget_url, timeout=120) as response:
            if response.status != 200:
                print(f"ERROR: HTTP {response.status} when downloading "
                      f"{nuget_url}")
                sys.exit(1)
            total = response.headers.get("Content-Length")
            total = int(total) if total else None
            chunks = []
            downloaded = 0
            while True:
                chunk = response.read(64 * 1024)
                if not chunk:
                    break
                chunks.append(chunk)
                downloaded += len(chunk)
                if total:
                    pct = downloaded * 100 // total
                    print(
                        f"\r  {downloaded // 1024}KB / {total // 1024}KB ({pct}%)",
                        end="",
                        flush=True)
                else:
                    print(f"\r  {downloaded // 1024}KB downloaded",
                          end="",
                          flush=True)
            print()
            package_bytes = io.BytesIO(b"".join(chunks))
    except Exception as e:
        print(f"ERROR: Failed to download: {e}")
        sys.exit(1)

    print(f"Extracting to {output_path} ...")
    os.makedirs(output_path, exist_ok=True)
    with zipfile.ZipFile(package_bytes, "r") as zip_ref:
        zip_ref.extractall(output_path)

    # Generate the version header
    write_version_header(output_path, version)

    # Write stamp file so we don't re-download next time
    with open(stamp, "w") as f:
        pass

    print("Done.")


def main():
    parser = argparse.ArgumentParser(
        description="Download the D3D12 Agility SDK for Dawn.")
    parser.add_argument(
        "--version",
        default=DEFAULT_VERSION,
        help=f"Agility SDK version to download (default: {DEFAULT_VERSION})")
    parser.add_argument(
        "--latest",
        action="store_true",
        help="Ignore --version and fetch the latest stable release")
    parser.add_argument("--output",
                        default=DEFAULT_OUTPUT,
                        help=f"Output directory (default: {DEFAULT_OUTPUT})")
    parser.add_argument("--force",
                        action="store_true",
                        help="Force re-download even if already present")
    parser.add_argument(
        "--stamp",
        default="",
        help="Path to write a stamp file on success (used by GN)")
    args = parser.parse_args()

    version = args.version
    if args.latest:
        version = get_latest_version()

    if os.path.isabs(args.output):
        output_path = args.output
    else:
        output_path = os.path.join(os.getcwd(), args.output)

    download_and_extract(args.force, version, output_path)

    # Write GN stamp file if requested
    if args.stamp:
        os.makedirs(os.path.dirname(args.stamp) or ".", exist_ok=True)
        with open(args.stamp, "w") as f:
            f.write(version)

    return 0


if __name__ == "__main__":
    sys.exit(main())
