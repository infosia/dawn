// This file exports the D3D12 Agility SDK symbols that tell the D3D12 loader
// to use the redistributable D3D12 runtime from the specified relative path.
//
// When DAWN_USE_AGILITY_SDK is defined (via the GN build arg dawn_use_agility_sdk),
// the D3D12 loader will look for D3D12Core.dll in the "D3D12/" subdirectory
// relative to the executable.
//
// See: https://devblogs.microsoft.com/directx/gettingstarted-dx12agility/

#if defined(DAWN_USE_AGILITY_SDK)
#include "dawn/native/d3d12/AgilitySDK.h"
// Auto-generated by tools/fetch_agility_sdk.py during the build.
// Contains AGILITY_SDK_VERSION matching the downloaded NuGet package version.
#include <windows.h>

#include "agility_sdk_version.h"
#include "dawn/common/Log.h"

extern "C" {

// The Agility SDK version.  The value comes from the generated header so it
// always matches the downloaded package – no manual update needed.
__declspec(dllexport) extern const unsigned int D3D12SDKVersion = AGILITY_SDK_VERSION;

// The relative path (from the executable) where D3D12Core.dll and
// d3d12SDKLayers.dll are located. This must end with a backslash or
// forward-slash and match the copy destination in BUILD.gn.
__declspec(dllexport) extern const char* D3D12SDKPath = ".\\D3D12\\";

}  // extern "C"

namespace dawn::native::d3d12 {

// LogAgilitySDKStatus() can be called during device initialization to verify
// that the Agility SDK D3D12Core.dll is actually being used.
//
// GetModuleHandleW("D3D12Core.dll") returns the already-loaded module.
// GetModuleFileNameW() gives its full path on disk.
// If the path does NOT contain "System32", it is our redistributable copy.
void LogAgilitySDKStatus() {
    HMODULE core = GetModuleHandleW(L"D3D12Core.dll");
    if (!core) {
        // d3d12.dll fell back to its own inbox implementation; our
        // D3D12Core.dll was never loaded (version not newer than system).
        dawn::InfoLog() << "[AgilitySDK] D3D12Core.dll is NOT loaded"
                           " - Agility SDK inactive (system fallback in use)";
    } else {
        wchar_t path[MAX_PATH] = {};
        GetModuleFileNameW(core, path, MAX_PATH);
        // If the path contains "System32" the loader used the system copy.
        bool isSystemCopy =
            (wcsstr(path, L"System32") != nullptr) || (wcsstr(path, L"system32") != nullptr);
        if (isSystemCopy) {
            dawn::InfoLog() << "[AgilitySDK] WARNING: D3D12Core.dll loaded from System32"
                               " — system version is >= our SDK ("
                            << AGILITY_SDK_VERSION << ")";
        } else {
            // wchar_t path → narrow string for the log
            char narrowPath[MAX_PATH] = {};
            WideCharToMultiByte(CP_UTF8, 0, path, -1, narrowPath, MAX_PATH, nullptr, nullptr);
            dawn::InfoLog() << "[AgilitySDK] OK: D3D12Core.dll loaded from: " << narrowPath;
        }
    }
}

}  // namespace dawn::native::d3d12

#endif  // defined(DAWN_USE_AGILITY_SDK)
